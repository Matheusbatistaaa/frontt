alter table public.usuarios
  add column if not exists turno text,
  add column if not exists horario_inicio time,
  add column if not exists horario_fim time,
  add column if not exists plantao boolean not null default false;

alter table public.internacoes
  add column if not exists risco text not null default 'normal',
  add column if not exists data_saida timestamptz;

create table if not exists public.prontuarios (
  id bigint generated by default as identity primary key,
  paciente_id bigint not null references public.pacientes(id) on delete cascade,
  internacao_id bigint references public.internacoes(id) on delete set null,
  queixa_principal text not null default '',
  historia_doenca text not null default '',
  avaliacao text not null default '',
  orientacoes text not null default '',
  sinais_vitais jsonb not null default '{"pa":"","fc":"","fr":"","temp":""}'::jsonb,
  prescricoes jsonb not null default '[]'::jsonb,
  exames jsonb not null default '[]'::jsonb,
  criado_por uuid references auth.users(id),
  atualizado_por uuid references auth.users(id),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint prontuarios_paciente_unico unique (paciente_id)
);

create index if not exists prontuarios_internacao_idx on public.prontuarios(internacao_id);

create or replace function public.set_prontuarios_atualizado_em()
returns trigger
language plpgsql
as $$
begin
  new.atualizado_em = now();
  return new;
end;
$$;

drop trigger if exists prontuarios_set_atualizado_em on public.prontuarios;
create trigger prontuarios_set_atualizado_em
before update on public.prontuarios
for each row execute function public.set_prontuarios_atualizado_em();

alter table public.prontuarios enable row level security;

drop policy if exists "prontuarios_leitura_autenticada" on public.prontuarios;
create policy "prontuarios_leitura_autenticada"
on public.prontuarios for select
to authenticated
using (true);

drop policy if exists "prontuarios_escrita_autenticada" on public.prontuarios;
create policy "prontuarios_escrita_autenticada"
on public.prontuarios for all
to authenticated
using (true)
with check (true);

grant select, insert, update on public.prontuarios to authenticated;
